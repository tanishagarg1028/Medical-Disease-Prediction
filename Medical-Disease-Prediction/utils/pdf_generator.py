from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.colors import darkblue
import os


def generate_pdf(patient, age, gender, disease, doctor, precautions):

    os.makedirs("reports", exist_ok=True)

    filename = f"reports/{patient.replace(' ', '_')}_Report.pdf"

    doc = SimpleDocTemplate(filename)

    styles = getSampleStyleSheet()

    title = styles["Heading1"]
    title.alignment = TA_CENTER
    title.textColor = darkblue

    heading = styles["Heading2"]

    normal = styles["BodyText"]

    story = []

    story.append(Paragraph("AI Medical Disease Prediction Report", title))
    story.append(Spacer(1, 20))

    story.append(Paragraph(f"<b>Patient Name:</b> {patient}", normal))
    story.append(Paragraph(f"<b>Age:</b> {age}", normal))
    story.append(Paragraph(f"<b>Gender:</b> {gender}", normal))

    story.append(Spacer(1, 15))

    story.append(Paragraph("<b>Prediction Result</b>", heading))
    story.append(Paragraph(f"Disease : {disease}", normal))
    story.append(Paragraph(f"Recommended Doctor : {doctor}", normal))

    story.append(Spacer(1, 15))

    story.append(Paragraph("<b>Precautions</b>", heading))

    for item in precautions:
        story.append(Paragraph("• " + item, normal))

    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            "Disclaimer: This prediction is generated by the Medical Disease Prediction System and should not replace professional medical advice.",
            normal
        )
    )

    doc.build(story)

    return filename